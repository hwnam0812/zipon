import { execFileSync } from "node:child_process";
import { mkdirSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import assert from "node:assert/strict";
import { parseFrame } from "../streamlit_ui/model.mjs";
const folder = join(tmpdir(), "opencode", "zipon-firmware-test");
mkdirSync(folder, { recursive: true });
const binary = join(folder, "firmware-v4-test");
execFileSync("g++", ["-std=c++17", "-Wall", "-Wextra", "-Werror", "-Wno-misleading-indentation", "-Itest/uno-stubs", "test/firmware-v4-native.cpp", "-o", binary], { stdio: "inherit" });
execFileSync(binary, [], { stdio: "inherit" });
const frames = execFileSync(binary, ["--usb-contract"], { encoding: "utf8" }).trim().split("\n").map(parseFrame);
const samples = frames.filter(frame => frame.type === "telemetry");
assert(frames.some(frame => frame.type === "boot") && frames.some(frame => frame.type === "ready"));
assert(frames.some(frame => frame.type === "ack" && !frame.applied && frame.reason === "gas_not_ready"));
assert(samples.some(sample => sample.gasRaw === 1023 && sample.distanceCm === 400));
assert(samples.some(sample => sample.gasRaw === 0 && sample.distanceCm === null));
assert(samples.some(sample => sample.gasRaw === null && sample.distanceCm === 8));
assert(samples.some(sample => sample.gasRaw === 100 && sample.distanceCm === 143.8));
assert(samples.some(sample => sample.led && !sample.buzzer));
assert(samples.some(sample => sample.led && sample.buzzer));
assert(!samples.at(-1).led && !samples.at(-1).buzzer);
console.log("통과 · 실제 스케치의 시작·연결·ADC 한계·거리·응답·출력 메시지를 앱 해석기로 확인 (격리 자료)");
